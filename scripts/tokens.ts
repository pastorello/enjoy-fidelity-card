// Turns design/tokens.json (design system "Enjoy Bar") into CSS custom
// properties. Light theme only (SPEC-platform §2): dark values are ignored.

type ThemedValue = Partial<Record<'light' | 'dark', string>>;

export type DesignTokens = {
  color: {
    themes: { id: string; name: string }[];
    tokens: { name: string; value: string | ThemedValue; usage?: string }[];
  };
  type: {
    fonts: { family: string; file: string; weight: string; style: string }[];
    families: Record<string, string>;
    groups: {
      name: string;
      family: string;
      styles: {
        name: string;
        family?: string;
        fontSize: string;
        lineHeight: number;
        fontWeight: number;
        letterSpacing?: string;
      }[];
    }[];
  };
  spacing: { tokens: ScaleToken[] };
  radius: { tokens: ScaleToken[] };
  size: { tokens: ScaleToken[] };
  breakpoint: { tokens: ScaleToken[] };
};

type ScaleToken = { name: string; value: string; usage?: string };

const REFERENCE = /^\{([a-z0-9-]+)\}$/;

function colorValue(raw: string, known: Set<string>): string {
  const match = REFERENCE.exec(raw);
  if (!match) return raw;
  const target = match[1] ?? '';
  if (!known.has(target)) {
    throw new Error(`Color token references unknown token "${target}"`);
  }
  return `var(--color-${target})`;
}

function decl(name: string, value: string | number): string {
  return `  --${name}: ${value};`;
}

export function buildTokensCss(tokens: DesignTokens): string {
  const known = new Set(tokens.color.tokens.map((t) => t.name));
  const lines: string[] = [];

  lines.push('  /* Color (light theme) */');
  for (const token of tokens.color.tokens) {
    let raw: string;
    if (typeof token.value === 'string') {
      raw = token.value;
    } else {
      if (token.value.light === undefined) {
        throw new Error(`Color token "${token.name}" has no light value`);
      }
      raw = token.value.light;
    }
    lines.push(decl(`color-${token.name}`, colorValue(raw, known)));
  }

  lines.push('', '  /* Font families */');
  for (const [name, stack] of Object.entries(tokens.type.families)) {
    lines.push(decl(`font-${name}`, stack));
  }

  for (const group of tokens.type.groups) {
    lines.push('', `  /* Type: ${group.name} */`);
    for (const style of group.styles) {
      const prefix = `type-${style.name}`;
      lines.push(
        decl(`${prefix}-family`, `var(--font-${style.family ?? group.family})`),
        decl(`${prefix}-size`, style.fontSize),
        decl(`${prefix}-line-height`, style.lineHeight),
        decl(`${prefix}-weight`, style.fontWeight),
        decl(`${prefix}-letter-spacing`, style.letterSpacing ?? 'normal'),
      );
    }
  }

  const scales = [
    ['Spacing', tokens.spacing.tokens],
    ['Radius', tokens.radius.tokens],
    ['Size', tokens.size.tokens],
    [
      'Breakpoints (reference only: custom properties do not work in media queries)',
      tokens.breakpoint.tokens,
    ],
  ] as const;
  for (const [title, scale] of scales) {
    lines.push('', `  /* ${title} */`);
    for (const token of scale) lines.push(decl(token.name, token.value));
  }

  return [
    '/* Generated by scripts/build-tokens.ts from design/tokens.json. Do not edit by hand. */',
    '',
    ':root {',
    ...lines,
    '}',
    '',
  ].join('\n');
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null;
}

function hasTokenList(value: unknown): boolean {
  return isRecord(value) && Array.isArray(value['tokens']);
}

/** Parses design/tokens.json, checking the sections the generator relies on. */
export function parseDesignTokens(text: string): DesignTokens {
  const data: unknown = JSON.parse(text);
  if (!isDesignTokens(data)) {
    throw new Error('design/tokens.json does not have the expected sections');
  }
  return data;
}

function isDesignTokens(data: unknown): data is DesignTokens {
  if (!isRecord(data)) return false;
  const type = data['type'];
  return (
    hasTokenList(data['color']) &&
    isRecord(type) &&
    isRecord(type['families']) &&
    Array.isArray(type['groups']) &&
    ['spacing', 'radius', 'size', 'breakpoint'].every((key) => hasTokenList(data[key]))
  );
}
