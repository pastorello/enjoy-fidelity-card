import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { buildTokensCss, parseDesignTokens, type DesignTokens } from './tokens.ts';

const tokens = parseDesignTokens(readFileSync('design/tokens.json', 'utf8'));
const css = buildTokensCss(tokens);

function minimal(overrides: Partial<DesignTokens> = {}): DesignTokens {
  return {
    color: { themes: [], tokens: [] },
    type: { fonts: [], families: {}, groups: [] },
    spacing: { tokens: [] },
    radius: { tokens: [] },
    size: { tokens: [] },
    breakpoint: { tokens: [] },
    ...overrides,
  };
}

describe('buildTokensCss', () => {
  it('emits palette colors as literal values', () => {
    expect(css).toContain('--color-enjoy-green: #00603a;');
    expect(css).toContain('--color-paper: #faf5f1;');
  });

  it('resolves semantic colors to the light theme, by reference', () => {
    expect(css).toContain('--color-surface: var(--color-paper);');
    expect(css).toContain('--color-ink: var(--color-black);');
    expect(css).toContain('--color-ink-muted: #595959;');
    expect(css).toContain('--color-focus-ring: var(--color-enjoy-green);');
    expect(css).not.toContain('#141414'); // dark theme stays out
  });

  it('emits font families and every text style', () => {
    expect(css).toContain('--font-brand: "Texturina", Georgia, serif;');
    expect(css).toContain('--type-screen-title-size: 28px;');
    expect(css).toContain('--type-screen-title-line-height: 1.15;');
    expect(css).toContain('--type-screen-title-weight: 700;');
    expect(css).toContain('--type-label-lg-letter-spacing: 0.01em;');
    expect(css).toContain('--type-body-letter-spacing: normal;');
    expect(css).toContain('--type-spaced-caps-condensed-family: var(--font-condensed);');
    expect(css).toContain('--type-body-family: var(--font-brand);');
  });

  it('emits spacing, radius, size and breakpoint scales', () => {
    expect(css).toContain('--space-3: 16px;');
    expect(css).toContain('--radius-none: 0px;');
    expect(css).toContain('--touch-target: 48px;');
    expect(css).toContain('--bp-tablet: 600px;');
  });

  it('marks the file as generated', () => {
    expect(css.startsWith('/* Generated by scripts/build-tokens.ts')).toBe(true);
  });

  it('throws on a reference to an unknown token', () => {
    const broken = minimal({
      color: {
        themes: [],
        tokens: [{ name: 'surface', value: { light: '{nope}', dark: '#000' } }],
      },
    });
    expect(() => buildTokensCss(broken)).toThrow(/nope/);
  });

  it('throws when a semantic color has no light value', () => {
    const broken = minimal({
      color: { themes: [], tokens: [{ name: 'surface', value: { dark: '#000' } }] },
    });
    expect(() => buildTokensCss(broken)).toThrow(/light/);
  });

  it('rejects a tokens file without the expected sections', () => {
    expect(() => parseDesignTokens('{"color": {}}')).toThrow(/expected sections/);
  });

  it('matches the committed src/styles/tokens.css (run `npm run tokens`)', () => {
    expect(readFileSync('src/styles/tokens.css', 'utf8')).toBe(css);
  });
});
