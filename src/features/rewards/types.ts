/** A catalog reward, as `app.rewards` stores it. */
export type Reward = { id: string; name: string; points: number; active: boolean };

/** A refusal of the server, no answer at all, or anything else. */
export type RewardWriteError =
  'name-taken' | 'invalid' | 'not-found' | 'forbidden' | 'network' | 'unknown';

export type RewardWriteResult =
  { ok: true; reward: Reward } | { ok: false; error: RewardWriteError };

/**
 * Everything the rewards feature needs from the backend. Writes resolve with a
 * `RewardWriteResult`; a misconfigured or unavailable server rejects with `ServerFaultError`.
 * The app uses the Supabase implementation; tests pass an in-memory fake.
 */
export type RewardsService = {
  /** The whole catalog, for the administrators, in `sortRewards()` order. */
  listAll(): Promise<Reward[]>;
  /** Only the active rewards, for `ledger`, by points and then name. */
  listActive(): Promise<Reward[]>;
  /** `id` is generated by the app when the form opens and kept until a save succeeds. */
  create(input: {
    id: string;
    name: string;
    points: number;
    active: boolean;
  }): Promise<RewardWriteResult>;
  update(id: string, input: { name: string; points: number }): Promise<RewardWriteResult>;
  setActive(id: string, active: boolean): Promise<RewardWriteResult>;
};
