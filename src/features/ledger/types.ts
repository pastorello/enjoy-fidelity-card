/** What a movement is: a purchase, a redemption (catalog or free reward) or a correction. */
export type MovementKind = 'purchase' | 'redemption' | 'correction';

/** A row of `app.movement_history`: a movement with who made it and who cancelled it. */
export type Movement = {
  id: string;
  operationId: string;
  customerId: string;
  kind: MovementKind;
  /** Purchase only: integer cents, 1..9.999.999; null otherwise. */
  amountCents: number | null;
  /** Signed: purchase >= 0, redemption < 0, correction = minus the corrected points. */
  points: number;
  /** Purchase only: the ratio in force when it was recorded; null otherwise. */
  centsPerPoint: number | null;
  /** Catalog redemption only; null for a free reward and the other kinds. */
  rewardId: string | null;
  /** Redemption only: the reward's name or the free reward's description. */
  description: string | null;
  operatorId: string;
  operatorName: string;
  createdAt: string;
  /** Correction only: the movement it cancels. */
  correctsMovementId: string | null;
  /** Set when a correction cancels this movement. */
  cancelledById: string | null;
  cancelledAt: string | null;
  /** Correction only: kind and time of the movement it cancels, for its text. */
  correctedKind: Exclude<MovementKind, 'correction'> | null;
  correctedCreatedAt: string | null;
};

/** What every write answers (`app.ledger_result`): the movement and the server's balance. */
export type LedgerResult = { movement: Movement; balance: number };

/** A refusal of the server (SPEC-ledger, "Errori → servizio"), no answer at all, or anything else. */
export type LedgerErrorKind =
  | 'insufficient-balance' // EC001
  | 'already-cancelled' // EC002
  | 'cancel-window-expired' // EC003
  | 'not-cancellable' // EC004
  | 'reward-unavailable' // EC005
  | 'customer-unavailable' // EC006
  | 'conflict' // EC007
  | 'forbidden' // 42501
  | 'invalid' // 22023
  | 'network'
  | 'unknown';

/**
 * Why a `LedgerService` call failed. Its message never carries customer data, so it can be
 * logged. A misconfigured or unavailable server rejects with `ServerFaultError` instead.
 */
export class LedgerError extends Error {
  readonly kind: LedgerErrorKind;

  constructor(kind: LedgerErrorKind) {
    super(`Ledger request failed (${kind})`);
    this.name = 'LedgerError';
    this.kind = kind;
  }
}

/** Where a page of the history starts: strictly older than this movement. */
export type MovementCursor = { createdAt: string; id: string };

/**
 * Everything the ledger feature needs from the backend. Every method rejects with a
 * `LedgerError` or a `ServerFaultError`. `operationId` is generated by the app and kept while
 * the outcome is uncertain: a resend answers the first result. The app uses the Supabase
 * implementation; tests pass an in-memory fake.
 */
export type LedgerService = {
  recordPurchase(input: {
    operationId: string;
    customerId: string;
    amountCents: number;
  }): Promise<LedgerResult>;
  redeemReward(input: {
    operationId: string;
    customerId: string;
    rewardId: string;
  }): Promise<LedgerResult>;
  redeemFreeReward(input: {
    operationId: string;
    customerId: string;
    description: string;
    points: number;
  }): Promise<LedgerResult>;
  cancelMovement(input: { operationId: string; movementId: string }): Promise<LedgerResult>;
  /** Newest first: 50 per page in Movimenti, 4 in the customer's page. */
  listMovements(
    customerId: string,
    options?: { before?: MovementCursor; limit?: number },
  ): Promise<Movement[]>;
};
