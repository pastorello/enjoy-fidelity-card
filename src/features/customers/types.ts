import type { CustomerErrorCode } from './errorCodes';

/** A customer as every customers RPC returns it (`app.customer_summary`). */
export type CustomerSummary = {
  id: string;
  /** For an anonymized customer, the technical "Cliente cancellato <8 chars>": never shown. */
  name: string;
  /** Stored form (trimmed, lowercase, unique), or null; null for an anonymized customer. */
  email: string | null;
  notes: string | null;
  /** When the data was erased on request (GDPR), or null. */
  anonymizedAt: string | null;
  /** Points; 0 until `ledger` exists. */
  balance: number;
  /** Last purchase or redemption, or null; null until `ledger` exists. */
  lastServedAt: string | null;
};

/** One row of the home list: what `app.list_customers` returns, nothing else. */
export type CustomerListRow = {
  id: string;
  name: string;
  balance: number;
  /** PostgREST's ISO string, microseconds included; null without purchases or redemptions. */
  lastActivityAt: string | null;
  /** PostgREST's ISO string, kept as received. */
  createdAt: string;
};

/**
 * The last row received, sent back unchanged (strings, never `Date`: a `Date` drops the
 * microseconds and the next page would skip or repeat rows); null for the first page.
 */
export type CustomerListCursor = { activityAt: string | null; createdAt: string; id: string };

/** The page size of `list`: a page shorter than this is the end of the list. */
export const CUSTOMER_LIST_PAGE_SIZE = 20;

export type CreateCustomerInput = {
  /** Generated by the app on the first send and kept while the outcome is uncertain. */
  operationId: string;
  name: string;
  /** As typed: the server normalizes it (`normalizeEmail`); blank means none. */
  email: string;
  privacyConsent: boolean;
  /** Blank means none. */
  notes: string;
};

export type UpdateCustomerInput = {
  id: string;
  name: string;
  /** As typed; blank removes the email. */
  email: string;
  notes: string;
};

/** A refusal of the server (its message-code), no answer at all, or anything else. */
export type CustomerErrorKind = CustomerErrorCode | 'network' | 'unknown';

/**
 * Why a `CustomerService` call failed. Its message never carries customer data, so it can be
 * logged. A misconfigured or unavailable server rejects with `ServerFaultError` instead.
 */
export class CustomerError extends Error {
  readonly kind: CustomerErrorKind;
  /** For `customer_name_taken` and `customer_email_taken`: the customer that already has the value. */
  readonly existingCustomerId: string | null;

  constructor(kind: CustomerErrorKind, existingCustomerId: string | null = null) {
    super(`Customer request failed (${kind})`);
    this.name = 'CustomerError';
    this.kind = kind;
    this.existingCustomerId = existingCustomerId;
  }
}

/**
 * Everything the customers feature needs from the backend. Every method rejects with a
 * `CustomerError` or a `ServerFaultError`. The app uses the Supabase implementation; tests pass
 * a fake.
 */
export type CustomerService = {
  /**
   * One page of the home list (at most 20 rows), latest activity first, then latest creation,
   * then id; never anonymized customers. From 2 characters `query` keeps the customers whose name
   * has every word, or whose email contains the whole text. `hasMore`: the page is full.
   */
  list(input: { query: string; after: CustomerListCursor | null }): Promise<{
    customers: CustomerListRow[];
    hasMore: boolean;
  }>;
  /** The customer, anonymized ones included, or null when the id does not exist. */
  get(id: string): Promise<CustomerSummary | null>;
  /** Idempotent on `operationId`: a repeated send returns the customer already created. */
  create(input: CreateCustomerInput): Promise<CustomerSummary>;
  update(input: UpdateCustomerInput): Promise<CustomerSummary>;
  /** Admins only (`forbidden` otherwise); repeating it changes nothing. */
  anonymize(id: string): Promise<CustomerSummary>;
};
