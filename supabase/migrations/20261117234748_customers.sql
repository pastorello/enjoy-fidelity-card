-- customers V1 (SPEC-customers.md, "Modello dati e regole di accesso"): the
-- customers table with its accent-insensitive unique name key, read access for
-- active operators and app.create_customer, idempotent on the operation id the
-- app generates. Writes happen only through security definer RPCs; errors are
-- raised with errcode P0001 and a code as message that the frontend translates.

create extension if not exists unaccent with schema extensions;

-- Name helpers ----------------------------------------------------------------------
-- Used by the table's check constraint, its generated key and the RPCs only, so
-- no API role may execute them.

-- Trimmed, with runs of inner whitespace reduced to one space.
create function private.clean_name(p_name text)
returns text
language sql
immutable
set search_path = ''
as $$
  select regexp_replace(btrim(p_name, E' \t\n\r\f\v'), '\s+', ' ', 'g');
$$;

-- The key two names must not share: case, accents and the typographic
-- apostrophe do not count ("Nicolò Rossi" = "nicolo  rossi", "D’Angelo" = "D'Angelo").
create function private.customer_name_key(p_name text)
returns text
language sql
immutable
set search_path = ''
as $$
  select lower(
    extensions.unaccent(
      'extensions.unaccent'::regdictionary,
      replace(private.clean_name(p_name), '’', '''')
    )
  );
$$;

-- E.164 form of a phone typed by an operator, or null when it is not a valid
-- number. Mirrored by normalizePhone in src/features/customers/phone.ts: spaces,
-- dots, dashes, slashes and parentheses dropped; a leading 00 means +; no prefix
-- means +39 (a landline keeps its 0: "0771 123456" -> +390771123456).
create function private.normalize_phone(p_phone text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_phone text := regexp_replace(p_phone, '[[:space:].()/-]', '', 'g');
begin
  if v_phone like '00%' then
    v_phone := '+' || substr(v_phone, 3);
  end if;
  if v_phone not like '+%' then
    v_phone := '+39' || v_phone;
  end if;
  if v_phone ~ '^\+[1-9][0-9]{6,14}$' then
    return v_phone;
  end if;
  return null;
end;
$$;

revoke execute on function
  private.clean_name(text), private.customer_name_key(text), private.normalize_phone(text)
  from public, anon, authenticated;

-- acting_operator_id -------------------------------------------------------------
-- Common body shared word for word with settings, rewards and ledger
-- (docs/specs/cross-review.md §2.1). tablet-kiosk redefines it later.
create or replace function private.acting_operator_id()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select private.current_operator_id();
$$;

revoke execute on function private.acting_operator_id() from public, anon, authenticated;

-- Table ------------------------------------------------------------------------------
create table app.customers (
  id uuid primary key default gen_random_uuid(),
  name text not null
    check (name = private.clean_name(name) and length(name) between 1 and 80),
  name_key text generated always as (private.customer_name_key(name)) stored,
  -- E.164, optional
  phone text check (phone ~ '^\+[1-9][0-9]{6,14}$'),
  -- the server's now() when the customer gave consent
  privacy_consent_at timestamptz not null,
  notes text check (length(notes) <= 500),
  created_at timestamptz not null default now(),
  created_by uuid not null references app.operators (id),
  -- generated by the app: a resent creation returns the customer already created
  create_operation_id uuid not null,
  anonymized_at timestamptz,
  constraint customers_create_operation_id_key unique (create_operation_id)
);

comment on table app.customers is
  'Bar customers. Written only by the customers RPCs; rows are never deleted, only anonymized.';

create unique index customers_name_key on app.customers (name_key);
create index customers_created_by_idx on app.customers (created_by);

-- Rows are written only through the RPCs below and never deleted.
revoke insert, update, delete, truncate on app.customers from authenticated, anon;

create policy customers_select_for_active_operators
  on app.customers
  for select
  to authenticated
  using ((select private.is_active_operator()));

-- What every customers RPC returns. ledger fills balance and last_served_at.
create type app.customer_summary as (
  id uuid,
  name text,
  phone text,
  notes text,
  anonymized_at timestamptz,
  balance int,
  last_served_at timestamptz
);

-- create_customer ------------------------------------------------------------------
create function app.create_customer(
  p_operation_id uuid,
  p_name text,
  p_phone text,
  p_privacy_consent boolean,
  p_notes text
)
returns app.customer_summary
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_name text := private.clean_name(p_name);
  v_phone text := nullif(btrim(p_phone, E' \t\n\r\f\v'), '');
  v_notes text := nullif(btrim(p_notes, E' \t\n\r\f\v'), '');
  v_row app.customers;
  v_taken_id uuid;
  v_constraint text;
begin
  if not private.is_active_operator() then
    raise exception 'not_operator' using errcode = 'P0001';
  end if;
  if p_operation_id is null then
    raise exception 'operation_id is required' using errcode = '22023';
  end if;

  -- A resent request: return what the first one created.
  select * into v_row from app.customers where create_operation_id = p_operation_id;
  if found then
    return (v_row.id, v_row.name, v_row.phone, v_row.notes, v_row.anonymized_at, 0, null)
      ::app.customer_summary;
  end if;

  if v_name is null or v_name = '' then
    raise exception 'name_required' using errcode = 'P0001';
  end if;
  if length(v_name) > 80 then
    raise exception 'name_too_long' using errcode = 'P0001';
  end if;
  if v_phone is not null then
    v_phone := private.normalize_phone(v_phone);
    if v_phone is null then
      raise exception 'phone_invalid' using errcode = 'P0001';
    end if;
  end if;
  if p_privacy_consent is not true then
    raise exception 'consent_required' using errcode = 'P0001';
  end if;
  if length(v_notes) > 500 then
    raise exception 'notes_too_long' using errcode = 'P0001';
  end if;

  select id into v_taken_id from app.customers where name_key = private.customer_name_key(v_name);
  if found then
    raise exception 'customer_name_taken' using errcode = 'P0001', detail = v_taken_id::text;
  end if;

  begin
    insert into app.customers (
      name, phone, privacy_consent_at, notes, created_by, create_operation_id
    )
    values (v_name, v_phone, now(), v_notes, private.acting_operator_id(), p_operation_id)
    returning * into v_row;
  exception when unique_violation then
    -- A concurrent request committed first: settle it with the constraint it hit.
    get stacked diagnostics v_constraint = constraint_name;
    if v_constraint = 'customers_create_operation_id_key' then
      select * into strict v_row from app.customers where create_operation_id = p_operation_id;
    elsif v_constraint = 'customers_name_key' then
      select id into strict v_taken_id
      from app.customers
      where name_key = private.customer_name_key(v_name);
      raise exception 'customer_name_taken' using errcode = 'P0001', detail = v_taken_id::text;
    else
      raise;
    end if;
  end;

  return (v_row.id, v_row.name, v_row.phone, v_row.notes, v_row.anonymized_at, 0, null)
    ::app.customer_summary;
end;
$$;

-- Explicit grants: never rely on the default privileges.
revoke execute on function app.create_customer(uuid, text, text, boolean, text) from public, anon;
grant execute on function app.create_customer(uuid, text, text, boolean, text) to authenticated;

-- update_customer ------------------------------------------------------------------
-- Any active operator; the last write wins. The phone sent empty clears it.
create function app.update_customer(
  p_customer_id uuid,
  p_name text,
  p_phone text,
  p_notes text
)
returns app.customer_summary
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_name text := private.clean_name(p_name);
  v_phone text := nullif(btrim(p_phone, E' \t\n\r\f\v'), '');
  v_notes text := nullif(btrim(p_notes, E' \t\n\r\f\v'), '');
  v_row app.customers;
  v_taken_id uuid;
  v_constraint text;
begin
  if not private.is_active_operator() then
    raise exception 'not_operator' using errcode = 'P0001';
  end if;

  -- Locked before the check, so an anonymization cannot slip in between.
  select * into v_row from app.customers where id = p_customer_id for update;
  if not found then
    raise exception 'customer_not_found' using errcode = 'P0001';
  end if;
  if v_row.anonymized_at is not null then
    raise exception 'customer_anonymized' using errcode = 'P0001';
  end if;

  if v_name is null or v_name = '' then
    raise exception 'name_required' using errcode = 'P0001';
  end if;
  if length(v_name) > 80 then
    raise exception 'name_too_long' using errcode = 'P0001';
  end if;
  if v_phone is not null then
    v_phone := private.normalize_phone(v_phone);
    if v_phone is null then
      raise exception 'phone_invalid' using errcode = 'P0001';
    end if;
  end if;
  if length(v_notes) > 500 then
    raise exception 'notes_too_long' using errcode = 'P0001';
  end if;

  select id into v_taken_id
  from app.customers
  where name_key = private.customer_name_key(v_name) and id <> p_customer_id;
  if found then
    raise exception 'customer_name_taken' using errcode = 'P0001', detail = v_taken_id::text;
  end if;

  begin
    update app.customers
    set name = v_name, phone = v_phone, notes = v_notes
    where id = p_customer_id
    returning * into v_row;
  exception when unique_violation then
    -- A concurrent request took the name first.
    get stacked diagnostics v_constraint = constraint_name;
    if v_constraint = 'customers_name_key' then
      select id into strict v_taken_id
      from app.customers
      where name_key = private.customer_name_key(v_name) and id <> p_customer_id;
      raise exception 'customer_name_taken' using errcode = 'P0001', detail = v_taken_id::text;
    else
      raise;
    end if;
  end;

  return (v_row.id, v_row.name, v_row.phone, v_row.notes, v_row.anonymized_at, 0, null)
    ::app.customer_summary;
end;
$$;

revoke execute on function app.update_customer(uuid, text, text, text) from public, anon;
grant execute on function app.update_customer(uuid, text, text, text) to authenticated;

-- anonymize_customer ---------------------------------------------------------------
-- Admins only (GDPR erasure): the row and its consent time stay, the personal
-- data goes. Repeating it on an anonymized customer changes nothing.
create function app.anonymize_customer(p_customer_id uuid)
returns app.customer_summary
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_row app.customers;
begin
  if not private.is_active_operator() then
    raise exception 'not_operator' using errcode = 'P0001';
  end if;
  if not private.is_admin() then
    raise exception 'forbidden' using errcode = 'P0001';
  end if;

  select * into v_row from app.customers where id = p_customer_id for update;
  if not found then
    raise exception 'customer_not_found' using errcode = 'P0001';
  end if;

  if v_row.anonymized_at is null then
    begin
      update app.customers
      set name = 'Cliente cancellato ' || left(v_row.id::text, 8),
          phone = null,
          notes = null,
          anonymized_at = now()
      where id = p_customer_id
      returning * into v_row;
    exception when unique_violation then
      -- Another customer already has that name (typed by hand, or the same
      -- first 8 characters of the id): the full id is unique.
      update app.customers
      set name = 'Cliente cancellato ' || v_row.id::text,
          phone = null,
          notes = null,
          anonymized_at = now()
      where id = p_customer_id
      returning * into v_row;
    end;
  end if;

  return (v_row.id, v_row.name, v_row.phone, v_row.notes, v_row.anonymized_at, 0, null)
    ::app.customer_summary;
end;
$$;

revoke execute on function app.anonymize_customer(uuid) from public, anon;
grant execute on function app.anonymize_customer(uuid) to authenticated;

-- Reads ------------------------------------------------------------------------------
-- security definer like the writes (the RLS would hide nothing from an operator
-- anyway), so each one checks the caller first. ledger replaces their bodies
-- with the real balance and the customers served today, keeping the signatures.

-- search_customers: by phone when the text is only digits (spaces, +, - and .
-- ignored) and has at least 3 of them, otherwise by name from 2 characters: every
-- word, through the name key, is contained in the customer's key. At most 21
-- rows (the 21st says there are more), never anonymized customers. Mirrored by
-- classifyQuery in src/features/customers/phone.ts.
create function app.search_customers(p_query text)
returns setof app.customer_summary
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_text text := private.clean_name(left(coalesce(p_query, ''), 80));
  v_digits text := regexp_replace(v_text, '[[:space:]+.-]', '', 'g');
  v_patterns text[];
begin
  if not private.is_active_operator() then
    raise exception 'not_operator' using errcode = 'P0001';
  end if;

  if v_digits ~ '^[0-9]+$' then
    if length(v_digits) < 3 then
      return;
    end if;
    -- A leading 00 stands for +, and the + is not among the digits searched.
    if v_digits like '00%' then
      v_digits := substr(v_digits, 3);
    end if;
    return query
      select c.id, c.name, c.phone, c.notes, c.anonymized_at, 0, null::timestamptz
      from app.customers c
      where c.anonymized_at is null
        and c.phone like '%' || v_digits || '%'
      order by c.name_key, c.id
      limit 21;
    return;
  end if;

  if length(v_text) < 2 then
    return;
  end if;
  -- One pattern per word; \, % and _ are escaped so they are searched literally.
  select array_agg(
    '%' || replace(replace(replace(private.customer_name_key(w), '\', '\\'), '%', '\%'), '_', '\_') || '%'
  )
  into v_patterns
  from unnest(string_to_array(v_text, ' ')) as w;

  return query
    select c.id, c.name, c.phone, c.notes, c.anonymized_at, 0, null::timestamptz
    from app.customers c
    where c.anonymized_at is null
      and c.name_key like all (v_patterns)
    order by c.name_key, c.id
    limit 21;
end;
$$;

revoke execute on function app.search_customers(text) from public, anon;
grant execute on function app.search_customers(text) to authenticated;

-- get_customer: anonymized customers too; no row when the id does not exist.
create function app.get_customer(p_customer_id uuid)
returns setof app.customer_summary
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not private.is_active_operator() then
    raise exception 'not_operator' using errcode = 'P0001';
  end if;

  return query
    select c.id, c.name, c.phone, c.notes, c.anonymized_at, 0, null::timestamptz
    from app.customers c
    where c.id = p_customer_id;
end;
$$;

revoke execute on function app.get_customer(uuid) from public, anon;
grant execute on function app.get_customer(uuid) to authenticated;

