-- rewards V1 (docs/specs/SPEC-rewards.md): the catalogue of fixed rewards,
-- readable by active operators and written only through the admin RPCs.
-- Rewards are never deleted, only deactivated: no delete function exists.

-- acting_operator_id -------------------------------------------------------------
-- Common body shared word for word with settings, customers and ledger
-- (docs/specs/cross-review.md §2.1). tablet-kiosk redefines it later.
create or replace function private.acting_operator_id()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select private.current_operator_id();
$$;

revoke execute on function private.acting_operator_id() from public, anon, authenticated;

-- Table ------------------------------------------------------------------------------
create table app.rewards (
  -- generated by the app at creation, so a resent creation is recognised
  id uuid primary key,
  name text not null check (name = btrim(name) and length(name) between 1 and 60),
  points int not null check (points between 1 and 99999),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid not null references app.operators (id),
  -- set to now() by the RPCs at every change
  updated_at timestamptz not null default now(),
  updated_by uuid not null references app.operators (id)
);

comment on table app.rewards is
  'Fixed rewards catalogue. Written only by the rewards RPCs; rows are never deleted, only deactivated.';

-- Names are unique regardless of case (leading and trailing spaces are never stored).
create unique index rewards_name_key on app.rewards (lower(name));
create index rewards_created_by_idx on app.rewards (created_by);
create index rewards_updated_by_idx on app.rewards (updated_by);

-- Rows are written only through the RPCs below and never deleted.
revoke insert, update, delete, truncate on app.rewards from authenticated, anon;

create policy rewards_select_for_active_operators
  on app.rewards
  for select
  to authenticated
  using ((select private.is_active_operator()));

-- create_reward ------------------------------------------------------------------------
-- Idempotent on p_id: a resent creation returns the existing row unchanged,
-- without validating it again. Checks run in this order: role, idempotency, values.
create function app.create_reward(p_id uuid, p_name text, p_points int, p_active boolean)
returns app.rewards
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_author uuid;
  v_name text := btrim(p_name);
  v_row app.rewards;
begin
  if not private.is_admin() then
    raise exception 'Only an admin can change the rewards' using errcode = '42501';
  end if;
  v_author := private.acting_operator_id();
  if v_author is null then
    raise exception 'No acting operator for this write' using errcode = '42501';
  end if;

  -- A resent request: return what the first one created.
  select * into v_row from app.rewards where id = p_id;
  if found then
    return v_row;
  end if;

  if p_id is null then
    raise exception 'id is required' using errcode = '23514';
  end if;
  if v_name is null or length(v_name) not between 1 and 60 then
    raise exception 'name must be 1 to 60 characters' using errcode = '23514';
  end if;
  if p_points is null or p_points not between 1 and 99999 then
    raise exception 'points must be between 1 and 99999, got %', p_points using errcode = '23514';
  end if;
  if p_active is null then
    raise exception 'active is required' using errcode = '23514';
  end if;

  -- Two concurrent requests with the same id make one row: the loser does nothing
  -- and reads the winner's row. A taken name raises 23505 on rewards_name_key.
  insert into app.rewards (id, name, points, active, created_by, updated_by)
  values (p_id, v_name, p_points, p_active, v_author, v_author)
  on conflict (id) do nothing;

  select * into strict v_row from app.rewards where id = p_id;
  return v_row;
end;
$$;

-- Explicit grants: never rely on the default privileges.
revoke execute on function app.create_reward(uuid, text, int, boolean) from public, anon;
grant execute on function app.create_reward(uuid, text, int, boolean) to authenticated;

-- update_reward ----------------------------------------------------------------------------
-- Changes name and points, never active. Resending it is safe by itself (same values).
-- Checks run in this order: role, existence (P0002), values.
create function app.update_reward(p_id uuid, p_name text, p_points int)
returns app.rewards
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_author uuid;
  v_name text := btrim(p_name);
  v_row app.rewards;
begin
  if not private.is_admin() then
    raise exception 'Only an admin can change the rewards' using errcode = '42501';
  end if;
  v_author := private.acting_operator_id();
  if v_author is null then
    raise exception 'No acting operator for this write' using errcode = '42501';
  end if;

  perform 1 from app.rewards where id = p_id for update;
  if not found then
    raise exception 'Reward % not found', p_id using errcode = 'P0002';
  end if;

  if v_name is null or length(v_name) not between 1 and 60 then
    raise exception 'name must be 1 to 60 characters' using errcode = '23514';
  end if;
  if p_points is null or p_points not between 1 and 99999 then
    raise exception 'points must be between 1 and 99999, got %', p_points using errcode = '23514';
  end if;

  -- A taken name raises 23505 on rewards_name_key.
  update app.rewards
  set name = v_name, points = p_points, updated_at = now(), updated_by = v_author
  where id = p_id
  returning * into strict v_row;
  return v_row;
end;
$$;

revoke execute on function app.update_reward(uuid, text, int) from public, anon;
grant execute on function app.update_reward(uuid, text, int) to authenticated;

-- set_reward_active ------------------------------------------------------------------------
-- Shows or hides a reward at the till and to the customer. Same order of checks.
create function app.set_reward_active(p_id uuid, p_active boolean)
returns app.rewards
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_author uuid;
  v_row app.rewards;
begin
  if not private.is_admin() then
    raise exception 'Only an admin can change the rewards' using errcode = '42501';
  end if;
  v_author := private.acting_operator_id();
  if v_author is null then
    raise exception 'No acting operator for this write' using errcode = '42501';
  end if;

  perform 1 from app.rewards where id = p_id for update;
  if not found then
    raise exception 'Reward % not found', p_id using errcode = 'P0002';
  end if;

  if p_active is null then
    raise exception 'active is required' using errcode = '23514';
  end if;

  update app.rewards
  set active = p_active, updated_at = now(), updated_by = v_author
  where id = p_id
  returning * into strict v_row;
  return v_row;
end;
$$;

revoke execute on function app.set_reward_active(uuid, boolean) from public, anon;
grant execute on function app.set_reward_active(uuid, boolean) to authenticated;

-- No API role can delete rewards: service_role gets every table privilege by
-- default (init migration), so delete and truncate are taken back here too.
revoke delete, truncate on app.rewards from service_role;
